"""Milestone 3: compare frbpe with the tokenizers of existing models.

Writes:
* results/comparison.csv             fertility, bytes/token, lossless rate,
                                     paired change vs frbpe-fr-32k
* results/segmentation_examples.md   how each tokenizer cuts a few sentences
* figures/comparison_fertility.png

Run scripts/download_reference.py and scripts/train_sentencepiece.py first.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from download_reference import DEFAULT_DIR, tiktoken_cache_dir  # noqa: E402
from frbpe.metrics import count_words, paired_relative_change, ratio_of_sums  # noqa: E402
from frbpe.reference import (  # noqa: E402
    Adapter,
    frbpe_adapter,
    sentencepiece_adapter,
    tiktoken_adapter,
)

TEST_SETS = {
    "wiki": Path("data/processed/test_wiki.jsonl"),
    "gutenberg": Path("data/processed/test_gutenberg.jsonl"),
}
REFERENCE_NAME = "frbpe-fr-32k"
SAME_CORPUS = "same 100 MB of FR Wikipedia"
N_BOOT = 1000

EXAMPLES = [
    "L'école d'été est fermée aujourd'hui.",
    "Qu’aurait-il fait s’il l’avait su ?",
    "Les élèves mangeaient des pommes.",
    "Le 14 juillet 1789, 1 000 personnes.",
    "anticonstitutionnellement",
    "Il est peut-être arrivé à Saint-Étienne.",
]


def build_adapters(models: Path, reference: Path) -> list[Adapter]:
    os.environ["TIKTOKEN_CACHE_DIR"] = str(tiktoken_cache_dir(reference).resolve())
    return [
        frbpe_adapter(models / "fr_32k.bpe", REFERENCE_NAME, SAME_CORPUS),
        frbpe_adapter(models / "gpt4_32k.bpe", "frbpe-gpt4regex-32k", SAME_CORPUS),
        sentencepiece_adapter(models / "sp_bpe_32k.model", "sentencepiece-bpe-32k", SAME_CORPUS),
        sentencepiece_adapter(models / "sp_unigram_32k.model", "sentencepiece-unigram-32k", SAME_CORPUS),
        sentencepiece_adapter(reference / "camembert_base.model", "camembert-base",
                              "French OSCAR (CamemBERT paper)"),
        sentencepiece_adapter(reference / "mistral_7b_v01.model", "mistral-7b-v0.1", "not disclosed"),
        tiktoken_adapter("gpt2", "gpt2", "English WebText (GPT-2 paper)"),
        tiktoken_adapter("cl100k_base", "cl100k_base (GPT-4)", "not disclosed"),
        tiktoken_adapter("o200k_base", "o200k_base (GPT-4o)", "not disclosed"),
    ]


def load_texts(path: Path) -> list[str]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line)["text"] for line in f]


def write_examples(adapters: list[Adapter], out: Path) -> None:
    lines = ["# Segmentation examples", "",
             "Generated by `scripts/compare_tokenizers.py`. Tokens are separated by `|`;"
             " a leading space is part of the token. `<0xNN>` is a raw byte.", ""]
    for sentence in EXAMPLES:
        lines += [f"## `{sentence}`", "", "| tokenizer | tokens | segmentation |", "|---|---|---|"]
        for a in adapters:
            ids = a.encode(sentence)
            shown = " \\| ".join(p.replace(" ", "␣").replace(" ", "⍽") for p in a.pieces(ids))
            lines.append(f"| {a.name} | {len(ids)} | {shown} |")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def plot(rows: list[dict], out: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharey=True)
    order = sorted({r["tokenizer"] for r in rows},
                   key=lambda n: next(r["fertility"] for r in rows
                                      if r["tokenizer"] == n and r["test_set"] == "wiki"))
    for ax, test_set in zip(axes, TEST_SETS):
        sel = {r["tokenizer"]: r for r in rows if r["test_set"] == test_set}
        y = np.arange(len(order))
        vals = [sel[n]["fertility"] for n in order]
        err = [[sel[n]["fertility"] - sel[n]["fertility_low"] for n in order],
               [sel[n]["fertility_high"] - sel[n]["fertility"] for n in order]]
        colors = ["#2a6f97" if sel[n]["trained_on"] == SAME_CORPUS else "#b0b0b0" for n in order]
        ax.barh(y, vals, xerr=err, color=colors, capsize=3)
        ax.set_yticks(y, [f"{n} ({sel[n]['vocab_size'] // 1000}k)" for n in order])
        ax.set_xlabel("tokens per word (lower is better)")
        ax.set_title(f"test set: {test_set}")
        ax.invert_yaxis()
        ax.grid(axis="x", alpha=0.3)
    fig.suptitle("French fertility. Blue: trained on my corpus. Grey: existing models.")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--models", type=Path, default=Path("models"))
    parser.add_argument("--reference", type=Path, default=DEFAULT_DIR)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--figures", type=Path, default=Path("figures"))
    args = parser.parse_args(argv)

    adapters = build_adapters(args.models, args.reference)
    texts = {name: load_texts(path) for name, path in TEST_SETS.items()}
    words = {n: np.array([count_words(t) for t in ts]) for n, ts in texts.items()}
    n_bytes = {n: np.array([len(t.encode("utf-8")) for t in ts]) for n, ts in texts.items()}

    # Two protocols. "document": each test document is encoded whole, the way
    # a model would see it. "paragraph": each paragraph is encoded alone and
    # newlines are not counted. The second removes two handicaps that
    # SentencePiece models have in the first one: they never saw a newline in
    # training (each costs a byte token) and the first word of a paragraph
    # lacks the "▁" prefix they add at the start of an input.
    tokens: dict[tuple[str, str], np.ndarray] = {}
    tokens_para: dict[tuple[str, str], np.ndarray] = {}
    lossless: dict[tuple[str, str], float] = {}
    for a in adapters:
        for test_set, ts in texts.items():
            counts, counts_para, exact = [], [], 0
            for t in ts:
                ids = a.encode(t)
                counts.append(len(ids))
                exact += a.decode(ids) == t
                counts_para.append(sum(len(a.encode(p)) for p in t.split("\n") if p))
            tokens[(a.name, test_set)] = np.array(counts)
            tokens_para[(a.name, test_set)] = np.array(counts_para)
            lossless[(a.name, test_set)] = exact / len(ts)
        print(f"done: {a.name}")

    rows = []
    for a in adapters:
        for test_set in TEST_SETS:
            tk = tokens[(a.name, test_set)]
            fert = ratio_of_sums(tk, words[test_set], n_boot=N_BOOT)
            bpt = ratio_of_sums(n_bytes[test_set], tk, n_boot=N_BOOT)
            change = paired_relative_change(tokens[(REFERENCE_NAME, test_set)], tk, n_boot=N_BOOT)
            change_para = paired_relative_change(
                tokens_para[(REFERENCE_NAME, test_set)], tokens_para[(a.name, test_set)], n_boot=N_BOOT
            )
            rows.append({
                "tokenizer": a.name, "family": a.family, "vocab_size": a.vocab_size,
                "trained_on": a.trained_on, "test_set": test_set, "tokens": int(tk.sum()),
                **fert.as_dict("fertility"), **bpt.as_dict("bytes_per_token"),
                **change.as_dict(f"change_vs_{REFERENCE_NAME}"),
                **change_para.as_dict(f"paragraph_change_vs_{REFERENCE_NAME}"),
                "lossless_docs": lossless[(a.name, test_set)],
            })

    args.results.mkdir(exist_ok=True)
    args.figures.mkdir(exist_ok=True)
    with (args.results / "comparison.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    write_examples(adapters, args.results / "segmentation_examples.md")
    plot(rows, args.figures / "comparison_fertility.png")

    key = f"change_vs_{REFERENCE_NAME}"
    for r in rows:
        print(f"{r['tokenizer']:28s} {r['vocab_size']:7d} {r['test_set']:9s} "
              f"fert {r['fertility']:.3f} [{r['fertility_low']:.3f},{r['fertility_high']:.3f}] "
              f"b/t {r['bytes_per_token']:.2f}  vs ref {100 * r[key]:+6.2f} % "
              f"[{100 * r[key + '_low']:+.2f},{100 * r[key + '_high']:+.2f}]  "
              f"paragraphs {100 * r['paragraph_' + key]:+6.2f} %  "
              f"lossless {100 * r['lossless_docs']:.1f} %")
    return 0


if __name__ == "__main__":
    sys.exit(main())
