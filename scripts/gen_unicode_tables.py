"""Generate c/src/unicode_tables.h from the Python `regex` module itself.

The C pre-tokenizer must classify every code point exactly like the Python
reference does. Rather than reading the Unicode database by hand, I ask the
same `regex` module that the reference uses, code point by code point, so
both sides agree on the Unicode version too:

* \\p{L}  letters          * \\p{N}  numbers
* \\s     whitespace       * \\w     word characters (for \\b)
* for each ASCII letter x, every code point matched by (?i:x)
  (for instance (?i:s) also matches U+017F LATIN SMALL LETTER LONG S)

Each class is stored as sorted [first, last] ranges, searched by bisection.
Run again after upgrading `regex`, and commit the result.
"""

from __future__ import annotations

import argparse
import string
import sys
from pathlib import Path

import regex

MAX_CODE_POINT = 0x10FFFF
CLASSES = {"letter": r"\p{L}", "number": r"\p{N}", "space": r"\s", "word": r"\w"}


def is_surrogate(cp: int) -> bool:
    return 0xD800 <= cp <= 0xDFFF


def ranges_of(pattern: str) -> list[tuple[int, int]]:
    rx = regex.compile(pattern)
    ranges: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX_CODE_POINT + 2):
        inside = cp <= MAX_CODE_POINT and not is_surrogate(cp) and rx.fullmatch(chr(cp)) is not None
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            ranges.append((start, cp - 1))
            start = None
    return ranges


def case_variants(letter: str) -> list[int]:
    rx = regex.compile(f"(?i:{letter})")
    return [cp for cp in range(MAX_CODE_POINT + 1)
            if not is_surrogate(cp) and rx.fullmatch(chr(cp)) is not None]


def render(tables: dict[str, list[tuple[int, int]]], folds: dict[str, list[int]]) -> str:
    out = [
        "/* Generated by scripts/gen_unicode_tables.py from the Python `regex`",
        f" * module {regex.__version__}. Do not edit by hand. */",
        "#ifndef FRBPE_UNICODE_TABLES_H",
        "#define FRBPE_UNICODE_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct { uint32_t first, last; } frbpe_range;",
        "",
    ]
    for name, ranges in tables.items():
        out.append(f"static const frbpe_range FRBPE_{name.upper()}[] = {{")
        for i in range(0, len(ranges), 4):
            row = ", ".join(f"{{0x{a:X}, 0x{b:X}}}" for a, b in ranges[i:i + 4])
            out.append(f"    {row},")
        out.append("};")
        out.append(f"#define FRBPE_{name.upper()}_LEN {len(ranges)}u")
        out.append("")
    # Case-insensitive matching. Inside ASCII, (?i:x) accepts exactly x and X
    # (checked in main). Outside ASCII it accepts a handful of code points,
    # listed here with the letter they fold to.
    extras = sorted((cp, letter) for letter, cps in folds.items() for cp in cps if cp >= 0x80)
    out.append("typedef struct { uint32_t cp; char letter; } frbpe_fold;")
    out.append("static const frbpe_fold FRBPE_FOLD_EXTRA[] = {")
    for cp, letter in extras:
        out.append(f"    {{0x{cp:X}, '{letter}'}},")
    out.append("};")
    out.append(f"#define FRBPE_FOLD_EXTRA_LEN {len(extras)}u")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def check_ascii_folds(folds: dict[str, list[int]]) -> None:
    """The C code relies on this: in ASCII, (?i:x) means x or X, nothing else."""
    for letter, cps in folds.items():
        ascii_part = sorted(cp for cp in cps if cp < 0x80)
        expected = sorted([ord(letter), ord(letter.upper())])
        if ascii_part != expected:
            raise SystemExit(f"(?i:{letter}) matches {ascii_part} in ASCII, expected {expected}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Unicode tables of the C encoder")
    parser.add_argument("--out", type=Path, default=Path("c/src/unicode_tables.h"))
    args = parser.parse_args(argv)
    tables = {name: ranges_of(pattern) for name, pattern in CLASSES.items()}
    folds = {letter: case_variants(letter) for letter in string.ascii_lowercase}
    check_ascii_folds(folds)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(tables, folds), encoding="utf-8", newline="\n")
    for name, ranges in tables.items():
        print(f"{name:7s} {len(ranges):5d} ranges")
    extras = {k: [hex(c) for c in v if c >= 0x80] for k, v in folds.items()}
    print("non-ASCII case variants:", {k: v for k, v in extras.items() if v})
    return 0


if __name__ == "__main__":
    sys.exit(main())
