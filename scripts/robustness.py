"""Milestone 6: how many extra tokens does a perturbation of the text cost?

For each tokenizer of milestone 3, each perturbation in src/frbpe/perturb.py
and each test set, counts the tokens of every document before and after the
perturbation and reports the paired relative change (same documents, bootstrap
over documents, 95 % interval). Also checks that decode(encode(x)) == x still
holds on the perturbed text.

Writes results/robustness.csv, results/robustness_examples.md and
figures/robustness.png. Needs the same files as scripts/compare_tokenizers.py.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from compare_tokenizers import TEST_SETS, build_adapters, load_texts  # noqa: E402
from download_reference import DEFAULT_DIR  # noqa: E402
from frbpe.metrics import count_words, paired_relative_change  # noqa: E402
from frbpe.perturb import PERTURBATIONS  # noqa: E402

N_BOOT = 1000
EXAMPLES = [
    "L'élève a révisé aujourd'hui.",
    "Qu'est-ce qu'il a dit ?",
]


def count_tokens(adapter, docs: list[str]) -> tuple[np.ndarray, float]:
    counts, exact = [], 0
    for d in docs:
        ids = adapter.encode(d)
        counts.append(len(ids))
        exact += adapter.decode(ids) == d
    return np.array(counts), exact / len(docs)


def write_examples(adapters, out: Path) -> None:
    lines = ["# Robustness examples", "",
             "Generated by `scripts/robustness.py`. `|` separates tokens, `␣` is a space,"
             " `⍽` a no-break space, `<0xNN>` a raw byte.", ""]
    for sentence in EXAMPLES:
        for name, perturb in [("original", lambda s: s), *PERTURBATIONS.items()]:
            text = perturb(sentence)
            if name != "original" and text == sentence:
                continue  # this perturbation does not touch the sentence
            lines += [f"## {name}: `{text}`", "", "| tokenizer | tokens | segmentation |",
                      "|---|---|---|"]
            for a in adapters:
                ids = a.encode(text)
                shown = " \\| ".join(
                    p.replace(" ", "␣").replace(" ", "⍽").replace("́", "◌́")
                    for p in a.pieces(ids))
                lines.append(f"| {a.name} | {len(ids)} | {shown} |")
            lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def plot(rows: list[dict], adapters, out: Path) -> None:
    """Tokens per word, original text first, then each perturbation. Absolute
    values rather than percentages, so tokenizers can be compared directly."""
    names = [a.name for a in adapters]
    perts = list(PERTURBATIONS)
    columns = ["original", *perts]
    fig, axes = plt.subplots(1, len(TEST_SETS), figsize=(14, 4.8), sharey=True)
    for ax, test_set in zip(axes, TEST_SETS):
        def cell(n, p):
            r = next(r for r in rows if r["tokenizer"] == n and r["test_set"] == test_set
                     and r["perturbation"] == (perts[0] if p == "original" else p))
            return r["fertility_original"] if p == "original" else r["fertility_perturbed"]
        grid = np.array([[cell(n, p) for p in columns] for n in names])
        im = ax.imshow(grid, cmap="Reds", vmin=1.0, vmax=4.0, aspect="auto")
        ax.set_xticks(range(len(columns)), columns, rotation=30, ha="right")
        ax.set_yticks(range(len(names)), names)
        for i in range(len(names)):
            for j in range(len(columns)):
                ax.text(j, i, f"{grid[i, j]:.2f}", ha="center", va="center", fontsize=8,
                        color="white" if grid[i, j] > 2.8 else "black")
        ax.set_title(f"test set: {test_set}")
    fig.colorbar(im, ax=axes, label="tokens per word (lower is better)", shrink=0.8)
    fig.suptitle("Tokens per word after each perturbation of the same text")
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--models", type=Path, default=Path("models"))
    parser.add_argument("--reference", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args(argv)

    adapters = build_adapters(args.models, args.reference)
    texts = {name: load_texts(path) for name, path in TEST_SETS.items()}
    perturbed = {(p, s): [f(d) for d in docs]
                 for p, f in PERTURBATIONS.items() for s, docs in texts.items()}
    # How much of the corpus each perturbation actually changes.
    touched = {(p, s): sum(a != b for a, b in zip(texts[s], perturbed[(p, s)])) / len(texts[s])
               for (p, s) in perturbed}

    # Relative changes alone mislead: a tokenizer that starts very low pays a
    # large percentage and may still end up lower than another one. So every
    # row also gives tokens per word, counted on the original words (none of
    # the perturbations adds or removes a word).
    n_words = {s: sum(count_words(d) for d in docs) for s, docs in texts.items()}
    rows = []
    for a in adapters:
        for test_set, docs in texts.items():
            base, _ = count_tokens(a, docs)
            for pert in PERTURBATIONS:
                tokens, lossless = count_tokens(a, perturbed[(pert, test_set)])
                change = paired_relative_change(base, tokens, n_boot=N_BOOT)
                rows.append({"tokenizer": a.name, "test_set": test_set, "perturbation": pert,
                             "docs_touched": touched[(pert, test_set)],
                             "fertility_original": base.sum() / n_words[test_set],
                             "fertility_perturbed": tokens.sum() / n_words[test_set],
                             **change.as_dict("change"), "lossless_docs": lossless})
        print(f"done: {a.name}")

    results = Path("results")
    with (results / "robustness.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    write_examples(adapters, results / "robustness_examples.md")
    plot(rows, adapters, Path("figures") / "robustness.png")
    for r in rows:
        print(f"{r['tokenizer']:28s} {r['test_set']:9s} {r['perturbation']:18s} "
              f"{100 * r['change']:+7.2f} % [{100 * r['change_low']:+.2f}, {100 * r['change_high']:+.2f}]"
              f"  touched {100 * r['docs_touched']:5.1f} %  lossless {100 * r['lossless_docs']:5.1f} %")
    return 0


if __name__ == "__main__":
    sys.exit(main())
